describe("rate limiter", () => {
  it("allows up to the limit then denies within the window", async () => {
    const { db, native } = createDatabase();
    try {
      const rule = { action: "menu_item.update_price", limit: 3, windowSeconds: 60 };
      const now = new Date("2026-01-15T10:00:00Z");

      const first = await consumeRateLimit(db, "user-1", rule, now);
      const second = await consumeRateLimit(db, "user-1", rule, now);
      const third = await consumeRateLimit(db, "user-1", rule, now);
      const fourth = await consumeRateLimit(db, "user-1", rule, now);

      expect(first.allowed).toBe(true);
      expect(second.allowed).toBe(true);
      expect(third.allowed).toBe(true);
      expect(fourth.allowed).toBe(false);
      expect(third.remaining).toBe(0);
      expect(fourth.retryAfterSeconds).toBeGreaterThan(0);
    } finally {
      native.close();
    }
  });

  it("resets on the next window", async () => {
    const { db, native } = createDatabase();
    try {
      const rule = { action: "menu_item.update_price", limit: 1, windowSeconds: 60 };
      const start = new Date("2026-01-15T10:00:00Z");

      expect((await consumeRateLimit(db, "user-1", rule, start)).allowed).toBe(true);
      expect((await consumeRateLimit(db, "user-1", rule, start)).allowed).toBe(false);

      const nextWindow = new Date("2026-01-15T10:01:00Z");
      expect((await consumeRateLimit(db, "user-1", rule, nextWindow)).allowed).toBe(true);
    } finally {
      native.close();
    }
  });

  it("keys on identity and action independently", async () => {
    const { db, native } = createDatabase();
    try {
      const priceRule = { action: "menu_item.update_price", limit: 1, windowSeconds: 60 };
      const imageRule = { action: "menu_item.replace_image", limit: 1, windowSeconds: 60 };
      const now = new Date("2026-01-15T10:00:00Z");

      expect((await consumeRateLimit(db, "user-1", priceRule, now)).allowed).toBe(true);
      expect((await consumeRateLimit(db, "user-1", priceRule, now)).allowed).toBe(false);

      // A different action, and a different identity, are both unaffected.
      expect((await consumeRateLimit(db, "user-1", imageRule, now)).allowed).toBe(true);
      expect((await consumeRateLimit(db, "user-2", priceRule, now)).allowed).toBe(true);
    } finally {
      native.close();
    }
  });

  it("prunes counters older than a day", async () => {
    const { db, native } = createDatabase();
    try {
      const rule = { action: "menu_item.update_price", limit: 5, windowSeconds: 60 };
      await consumeRateLimit(db, "user-1", rule, new Date("2026-01-10T10:00:00Z"));

      await pruneRateLimitCounters(db, new Date("2026-01-15T10:00:00Z"));
      const after = await consumeRateLimit(db, "user-1", rule, new Date("2026-01-15T10:00:00Z"));
      expect(after.allowed).toBe(true);
    } finally {
      native.close();
    }
  });
});
